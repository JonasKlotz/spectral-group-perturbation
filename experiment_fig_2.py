"""Fig. 2: qualitative Occlusion explanations of JP and SGP.

`run` computes the JP map and the three SGP group maps (C1, C2, C3) with Occlusion and the
Global mean baseline on ConvNeXtV2-Base for all 1000 test pairs of Table II and saves them.
`plot` renders chosen pairs for the paper: RGB image with the reference map of the class
outlined, the JP map and the rectified group maps, all maps of one image on one colour
scale, plus values.tex with the relevance share s_i of every group (sum of its rectified
map over the sum of all group maps).

    python experiment_fig_2.py run [--shard i/n] [--limit N]
    python experiment_fig_2.py plot --pairs 79139:11 79224:11
"""
import argparse
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from sgp.config import RESULTS, pairs_path
from sgp.data import BENv2
from sgp.runner import Method, cli, run

OUT = f"{RESULTS}/fig_2"
MODEL, SPLIT, N_PAIRS = "convnextv2", "test", 1000
METHODS = [Method("occlusion_jp_gmean", "occlusion", 1, "gmean", {"window": 50, "stride": 5}),
           Method("occlusion_sgp_gmean", "occlusion", 3, "gmean", {"window": 50, "stride": 8})]
UP = 4  # nearest-neighbour upsampling of the 120 x 120 px images
CMAP, OUTLINE = "Oranges", "#ffd400"


def run_fig_2(model, **kwargs):
    run(model, SPLIT, pairs_path(model, SPLIT, N_PAIRS), METHODS, OUT, metrics=False, ood=False, save_maps=True,
        **kwargs)


def rgb(x):
    img = x[[2, 1, 0]].transpose(1, 2, 0)  # B04, B03, B02
    lo, hi = np.percentile(img, 2), np.percentile(img, 98)
    return np.clip((img - lo) / max(hi - lo, 1e-6), 0, 1)


def save_rgb(path, x, mask):
    n = x.shape[-1] * UP
    fig = plt.figure(figsize=(n / 100, n / 100), dpi=100)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.imshow(np.kron(rgb(x), np.ones((UP, UP, 1))), interpolation="nearest")
    ax.contour(np.kron(mask.astype(float), np.ones((UP, UP))), levels=[0.5], colors=OUTLINE, linewidths=3.5)
    ax.set_axis_off()
    fig.savefig(path, dpi=100)
    plt.close(fig)


def save_map(path, a, top):
    v = np.clip(a / max(top, 1e-12), 0, 1)
    # the lightest 3 % of the colour ramp is left out so that zero stays visible on white paper
    plt.imsave(path, np.kron(0.03 + 0.95 * v, np.ones((UP, UP))), cmap=CMAP, vmin=0, vmax=1)


def plot(pairs):
    maps_dir = f"{OUT}/{MODEL}/maps"
    os.makedirs(f"{OUT}/img", exist_ok=True)
    dataset = BENv2(SPLIT)
    tex = ["% generated by experiment_fig_2.py",
           "\\providecommand{\\figshare}[2]{\\csname figshare@#1@#2\\endcsname}",
           "\\providecommand{\\figmax}[1]{\\csname figmax@#1\\endcsname}"]
    for sid, c in pairs:
        x, _, s = dataset.batch([sid])
        jp = np.maximum(np.load(f"{maps_dir}/{METHODS[0].name}/{sid}_{c}.npy"), 0)[0]
        groups = np.maximum(np.load(f"{maps_dir}/{METHODS[1].name}/{sid}_{c}.npy"), 0)
        top = max(jp.max(), groups.max())
        save_rgb(f"{OUT}/img/{sid}_rgb.png", x[0], s[0, c, 0] > 0)
        save_map(f"{OUT}/img/{sid}_jp.png", jp, top)
        shares = groups.sum(axis=(1, 2)) / groups.sum()
        for k, (m, share) in enumerate(zip(groups, shares), start=1):
            save_map(f"{OUT}/img/{sid}_c{k}.png", m, top)
            tex.append(f"\\expandafter\\def\\csname figshare@{sid}@C{k}\\endcsname{{{round(100 * share)}}}")
        tex.append(f"\\expandafter\\def\\csname figmax@{sid}\\endcsname{{{top:.2f}}}")
        print(f"{sid} class {c}: max {top:.2f}, shares " + ", ".join(f"C{k} {v:.2f}" for k, v in enumerate(shares, 1)))
    ramp = np.tile(np.linspace(0, 1, 512), (16, 1))
    plt.imsave(f"{OUT}/img/colorbar.png", 0.03 + 0.95 * ramp, cmap=CMAP, vmin=0, vmax=1)
    with open(f"{OUT}/values.tex", "w") as f:
        f.write("\n".join(tex) + "\n")
    print(f"wrote {OUT}/img and {OUT}/values.tex")


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == "plot":
        p = argparse.ArgumentParser(description="render chosen pairs of Fig. 2")
        p.add_argument("cmd")
        p.add_argument("--pairs", nargs="+", required=True, help="sample:class, e.g. 79139:11")
        args = p.parse_args()
        plot([tuple(int(v) for v in pair.split(":")) for pair in args.pairs])
    else:
        cli(__doc__, run_fig_2, lambda: print("Fig. 2 has no table; use: plot --pairs SID:CLASS ..."), [MODEL])
